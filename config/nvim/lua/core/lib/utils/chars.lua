    local categories = {
        os = M.os_icons,
        file = M.file_icons,
        filetype = M.filetype_icons,
    }

    -- Directly access the category table
    local module = categories[category]
    if module then
        return module[name]
    end

    -- Return nil if the category or name doesn't exist
    return nil
end

