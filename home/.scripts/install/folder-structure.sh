#!/usr/bin/env bash
# install-structure.sh
# Creates DESIGN and WORKSPACE folder structures
# Author: you
# Usage:
#   ./install-structure.sh

set -euo pipefail

# ---------------- VARIABLES ----------------
DESIGN="${HOME}/Data/Design"
WORKSPACE="${HOME}/workspace"

# ---------------- HELPERS ----------------
function log() {
    echo -e "$@"
}

function mkd() {
    local dir="$1"
    if [ ! -d "$dir" ]; then
        mkdir -p "$dir"
        log "Created: $dir"
    else
        log "Exists:  $dir"
    fi
}

function create_readme() {
    local dir="$1"
    local title="$2"
    local desc="$3"
    local file="${dir}/README.md"
    if [ ! -f "$file" ]; then
        cat > "$file" <<EOF
# ${title}

${desc}

Generated by install-structure.sh
EOF
        log "Created README.md in $dir"
    fi
}

# ---------------- DESIGN STRUCTURE ----------------
function create_design_structure() {
    log "\nCreating DESIGN structure at $DESIGN"

    mkd "$DESIGN"

    # Top-level
    mkd "$DESIGN/Projects"
    mkd "$DESIGN/Templates"
    mkd "$DESIGN/Assets"
    mkd "$DESIGN/UI-Kit"
    mkd "$DESIGN/Branding"
    mkd "$DESIGN/Tools"
    mkd "$DESIGN/Clients"
    mkd "$DESIGN/Archives"
    mkd "$DESIGN/tmp"

    # Assets subfolders
    mkd "$DESIGN/Assets/Icons/svg"
    mkd "$DESIGN/Assets/Icons/png"
    mkd "$DESIGN/Assets/Fonts"
    mkd "$DESIGN/Assets/StockPhotos"
    mkd "$DESIGN/Assets/Patterns"
    mkd "$DESIGN/Assets/Textures"
    mkd "$DESIGN/Assets/Kits"

    # UI-Kit
    mkd "$DESIGN/UI-Kit/figma-exports"
    mkd "$DESIGN/UI-Kit/sketch-files"
    mkd "$DESIGN/UI-Kit/components"

    # Branding
    mkd "$DESIGN/Branding/guidelines"
    mkd "$DESIGN/Branding/logos"
    mkd "$DESIGN/Branding/color-palettes"

    # Tools
    mkd "$DESIGN/Tools/scripts"
    mkd "$DESIGN/Tools/presets"
    mkd "$DESIGN/Tools/exports"

    # Clients
    mkd "$DESIGN/Clients/invoices"
    mkd "$DESIGN/Clients/contacts"
    mkd "$DESIGN/Clients/proposals"

    # Templates
    mkd "$DESIGN/Templates/web"
    mkd "$DESIGN/Templates/print"
    mkd "$DESIGN/Templates/social"
    mkd "$DESIGN/Templates/gfx"
    mkd "$DESIGN/Templates/texture-kits"

    # create_readme "$DESIGN" "Design Workspace" "Main design folder structure"
}

# ---------------- WORKSPACE STRUCTURE ----------------
function create_workspace_structure() {
    log "\nCreating WORKSPACE structure at $WORKSPACE"

    mkd "$WORKSPACE"

    mkd "$WORKSPACE/00_Inbox"
    mkd "$WORKSPACE/10_Areas/coding"
    mkd "$WORKSPACE/10_Areas/school"

    mkd "$WORKSPACE/20_Projects/l2dgame"
    mkd "$WORKSPACE/20_Projects/vstbutmys"

    mkd "$WORKSPACE/30_Resources/audio"
    mkd "$WORKSPACE/30_Resources/Excalidraw"
    mkd "$WORKSPACE/30_Resources/Images"
    mkd "$WORKSPACE/30_Resources/PDFs"

    mkd "$WORKSPACE/90_Archives"
    touch "$WORKSPACE/90_Archives/theme.bte"

    mkd "$WORKSPACE/Excalidraw"
    mkd "$WORKSPACE/_templates"

    # create_readme "$WORKSPACE" "Workspace" "Workspace structure for projects, resources, and notes"
}

# ---------------- EXECUTE ----------------
create_design_structure
create_workspace_structure

log "\nAll folders have been created successfully!"
