-- Super-tap interrupts (generated).
--
-- The overview opens on RELEASE of a bare Super tap. While Super is held,
-- pressing any other key must cancel that pending toggle, or e.g.
-- Ctrl+Super+M (KinetiX) opens the overview as well when Super comes up.
--
-- Up to 0.55 one `binditn = Super, catchall` did this for every key. On 0.56
-- catchall is submap-only ("hl.bind: catchall keybinds are only allowed in
-- submaps"), so instead every SUPER combo gets a second, `transparent` bind
-- firing the interrupt. Transparent means Hyprland keeps scanning after it,
-- so the real bind on the same combo still runs.
--
-- These use their own global (superComboInterrupt) rather than the catchall's
-- searchToggleReleaseInterrupt: that handler ignores interrupts arriving within
-- 80ms of the Super press, because the old catchall fired once for the Super
-- press itself. A bind on SUPER+<key> can only fire if <key> really was pressed,
-- so it needs no such guard — and 80ms is easily beaten by a fast combo.

